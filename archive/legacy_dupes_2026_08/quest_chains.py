def get_available_chains(player_level: int, credits: int, faction_rep: dict) -> list:
    """Return quest chains available to this player."""
    available = []
    for chain in QUEST_CHAINS:
        if player_level < chain.get("min_level", 0):
            continue
        if credits < chain.get("min_credits", 0):
            continue
        faction = chain.get("faction")
        if faction and faction_rep.get(faction, 0) < chain.get("min_rep", 0):
            continue
        available.append({"id": chain["id"], "name": chain["name"],
                          "faction": faction, "stages": len(chain["stages"]),
                          "description": chain["description"]})
    return available


def get_chain_stage(chain_id: str, stage_index: int) -> dict:
    """Get specific stage from a chain."""
    for chain in QUEST_CHAINS:
        if chain["id"] == chain_id:
            if 0 <= stage_index < len(chain["stages"]):
                stage = chain["stages"][stage_index]
                return {**stage, "chain_id": chain_id, "chain_name": chain["name"],
                        "stage_num": stage_index + 1, "total_stages": len(chain["stages"]),
                        "is_last": stage_index == len(chain["stages"]) - 1}
    return None
